/** Curated, tree-shakeable icon set the header menu (and its admin editor) can use — keeps the client bundle from pulling in the entire lucide-react library. */
export const MENU_ICON_OPTIONS: Record<string, LucideIcon> = {
  Coffee,
  Sandwich,
  Moon,
  Cookie,
  Leaf,
  Flame,
  Drumstick,
  Beef,
  Fish,
  Sprout,
  Salad,
  Soup,
  Wheat,
  Snowflake,
  DollarSign,
  Apple,
  Users,
  UtensilsCrossed,
  LayoutGrid,
  BookOpen,
  Info,
  Mail,
  Star,
  Clock,
  Tag,
  Egg,
  Milk,
  Carrot,
  Pizza,
  IceCreamCone,
  Cherry,
};

export function getMenuIcon(name: string | null | undefined): LucideIcon {
  return (name && MENU_ICON_OPTIONS[name]) || Tag;
}
